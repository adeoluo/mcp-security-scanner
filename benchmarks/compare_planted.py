"""Score mcpscan, Semgrep and Bandit on the planted-vulnerability benchmark.

The benchmark is generated by `mcpscan bench --out DIR`. Every tool is scored with the same rule:
a vulnerable case counts as detected when the tool reports a finding of the case's category
anywhere in the case directory; a safe look-alike counts as a false positive when it does.

Usage (from the repository root, after `make build`):
  uv run --project benchmarks python benchmarks/compare_planted.py \
      --mcpscan bin/mcpscan --work ../.bench-data/mcp-security-scanner/planted
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import shutil
import subprocess
import sys
import time
from collections import defaultdict
from pathlib import Path

from stats import Counts, fmt

SEMGREP_VERSION = "1.183.0"
BANDIT_VERSION = "1.9.4"
SEMGREP_CONFIGS = [
    "p/default",
    "p/security-audit",
    "p/owasp-top-ten",
    "p/secrets",
    "p/gitleaks",
    "p/javascript",
    "p/typescript",
    "p/python",
    "p/nodejs",
    "p/command-injection",
]

MCPSCAN_RULES = {
    "MCP101": "command-injection",
    "MCP102": "command-injection",
    "MCP111": "path-traversal",
    "MCP121": "ssrf",
    "MCP131": "secrets",
    "MCP132": "secrets",
}

# Bandit tests whose purpose is one of the benchmark categories. Import-only warnings (B404),
# missing timeouts (B113) and argv-without-shell notes (B603, B607) are not counted.
BANDIT_RULES = {
    "B602": "command-injection",
    "B604": "command-injection",
    "B605": "command-injection",
    "B601": "command-injection",
    "B609": "command-injection",
    "B307": "command-injection",
    "B102": "command-injection",
    "B310": "ssrf",
    "B105": "secrets",
    "B106": "secrets",
    "B107": "secrets",
}

_SEMGREP_PATTERNS = [
    ("secrets", re.compile(r"secrets|gitleaks|hardcoded|api-key|token|password", re.I)),
    ("ssrf", re.compile(r"ssrf|urllib|tainted-url|request-forgery|dynamic-url|http-request", re.I)),
    (
        "path-traversal",
        re.compile(r"path-traversal|path-join|non-literal-fs|tainted-filename|open-redirect-path|file-inclusion", re.I),
    ),
    (
        "command-injection",
        re.compile(
            r"child-process|shell|subprocess|os-system|command|exec|eval|code-injection|spawn|new-function", re.I
        ),
    ),
]


def semgrep_category(check_id: str) -> str | None:
    """Map a Semgrep rule id to a benchmark category, or None when it is about something else."""
    if "insecure-transport" in check_id or "request-with-http" in check_id:
        return None
    for cat, pat in _SEMGREP_PATTERNS:
        if pat.search(check_id):
            return cat
    return None


def case_of(path: str, root: Path) -> str | None:
    """Return the case id (first directory under the source root) of a reported path."""
    try:
        rel = Path(path).resolve().relative_to(root.resolve())
    except ValueError:
        return None
    return rel.parts[0] if len(rel.parts) > 1 else None


def score(cases: list[dict], detections: dict[str, set[str]], langs: set[str] | None = None) -> dict[str, Counts]:
    """Group counts by category|lang|tier, plus an overall entry."""
    groups: dict[str, Counts] = defaultdict(Counts)
    for c in cases:
        if langs and c["lang"] not in langs:
            continue
        hit = c["category"] in detections.get(c["id"], set())
        groups[f"{c['category']}|{c['lang']}|{c['tier']}"].add(c["vulnerable"], hit)
        groups["overall"].add(c["vulnerable"], hit)
    return dict(groups)


def run_timed(cmd: list[str]) -> tuple[float, subprocess.CompletedProcess]:
    t0 = time.perf_counter()
    proc = subprocess.run(cmd, capture_output=True, text=True)
    return time.perf_counter() - t0, proc


def mcpscan_detections(binary: str, src: Path, cases: list[dict]) -> tuple[dict[str, set[str]], float]:
    det: dict[str, set[str]] = {}
    total = 0.0
    for c in cases:
        secs, proc = run_timed([binary, "scan", str(src / c["id"]), "--format", "json", "--fail-on", "none"])
        total += secs
        if proc.returncode != 0:
            raise RuntimeError(proc.stderr)
        det[c["id"]] = {
            MCPSCAN_RULES[f["rule_id"]] for f in json.loads(proc.stdout)["findings"] if f["rule_id"] in MCPSCAN_RULES
        }
    return det, total


def merge_rule_packs(texts: list[str]) -> tuple[str, int]:
    """Merge registry rule packs into one YAML document, keeping the first copy of each rule id."""
    seen: set[str] = set()
    blocks: list[str] = []
    for text in texts:
        body = text.split("rules:\n", 1)[-1]
        for block in ("\n" + body).split("\n- id: ")[1:]:
            rule_id = block.split("\n", 1)[0].strip()
            if rule_id not in seen:
                seen.add(rule_id)
                blocks.append("- id: " + block.rstrip("\n"))
    return "rules:\n" + "\n".join(blocks) + "\n", len(seen)


def fetch_semgrep_rules(work: Path) -> list[Path]:
    """Download the registry rule packs once and merge them without duplicate rules, so the timed
    run measures analysis rather than downloads (the packs overlap: p/default contains most others)."""
    rules_dir = work / "semgrep-rules"
    rules_dir.mkdir(parents=True, exist_ok=True)
    texts = []
    for c in SEMGREP_CONFIGS:
        dest = rules_dir / (c.replace("/", "_") + ".yml")
        if not dest.exists():
            subprocess.run(["curl", "-fsSL", "-o", str(dest), f"https://semgrep.dev/c/{c}"], check=True)
        texts.append(dest.read_text())
    merged, _ = merge_rule_packs(texts)
    out = work / "semgrep-merged.yml"
    out.write_text(merged)
    return [out]


def semgrep_detections(
    src: Path, work: Path, rule_files: list[Path] | None = None
) -> tuple[dict[str, set[str]], float, dict]:
    out = work / "semgrep.json"
    cmd = [
        "uv",
        "tool",
        "run",
        f"semgrep=={SEMGREP_VERSION}",
        "scan",
        "--json",
        "--metrics=off",
        "--no-git-ignore",
        "--quiet",
        "-o",
        str(out),
    ]
    for c in rule_files or SEMGREP_CONFIGS:
        cmd += ["--config", str(c)]
    secs, proc = run_timed([*cmd, str(src)])
    if not out.exists():
        raise RuntimeError(proc.stderr)
    data = json.loads(out.read_text())
    det: dict[str, set[str]] = defaultdict(set)
    rules: dict[str, int] = defaultdict(int)
    for r in data["results"]:
        cat = semgrep_category(r["check_id"])
        cid = case_of(r["path"], src)
        if cat and cid:
            det[cid].add(cat)
            rules[r["check_id"]] += 1
    return dict(det), secs, dict(rules)


def bandit_detections(src: Path, work: Path) -> tuple[dict[str, set[str]], float]:
    out = work / "bandit.json"
    secs, proc = run_timed(
        ["uv", "tool", "run", f"bandit=={BANDIT_VERSION}", "-r", str(src), "-f", "json", "-o", str(out), "-q"]
    )
    if not out.exists():
        raise RuntimeError(proc.stderr)
    det: dict[str, set[str]] = defaultdict(set)
    for r in json.loads(out.read_text())["results"]:
        cat = BANDIT_RULES.get(r["test_id"])
        cid = case_of(r["filename"], src)
        if cat and cid:
            det[cid].add(cat)
    return dict(det), secs


def markdown(results: dict) -> str:
    lines = [
        "| Category | Language | Tier | Tool | Recall | FPR on safe look-alikes | TP / FN / FP / TN |",
        "|---|---|---|---|---:|---:|---|",
    ]
    keys = sorted({k for t in results["tools"].values() for k in t["groups"] if k != "overall"})
    for key in keys:
        cat, lang, tier = key.split("|")
        for name, t in results["tools"].items():
            g = t["groups"].get(key)
            if g is None:
                continue
            lines.append(
                f"| {cat} | {lang} | {tier} | {name} | {fmt(g['recall'])} | {fmt(g['fpr'])} | "
                f"{g['tp']} / {g['fn']} / {g['fp']} / {g['tn']} |"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mcpscan", default="bin/mcpscan")
    ap.add_argument("--work", type=Path, required=True)
    ap.add_argument("--seed", type=int, default=20261103)
    ap.add_argument("--out", type=Path, default=Path("benchmarks/results/planted.json"))
    ap.add_argument("--skip-external", action="store_true", help="score mcpscan only")
    ap.add_argument(
        "--semgrep-local-rules",
        action="store_true",
        help="download and merge the rule packs first (same results; slower on this machine than registry configs)",
    )
    args = ap.parse_args(argv)

    shutil.rmtree(args.work, ignore_errors=True)
    gen = subprocess.run(
        [args.mcpscan, "bench", "--seed", str(args.seed), "--out", str(args.work), "--format", "json"],
        capture_output=True,
        text=True,
        check=True,
    )
    bench = json.loads(gen.stdout)
    src = args.work / "source"
    cases = json.loads((src / "truth.json").read_text())["cases"]

    tools: dict[str, dict] = {}
    det, secs = mcpscan_detections(args.mcpscan, src, cases)
    whole_secs, _ = run_timed([args.mcpscan, "scan", str(src), "--format", "json", "--fail-on", "none"])
    tools["mcpscan"] = {
        "seconds_per_case_total": secs,
        "seconds_whole_tree": whole_secs,
        "groups": {k: v.as_dict() for k, v in score(cases, det).items()},
    }
    if not args.skip_external:
        rule_files = fetch_semgrep_rules(args.work) if args.semgrep_local_rules else None
        det, secs, rules = semgrep_detections(src, args.work, rule_files)
        tools[f"semgrep {SEMGREP_VERSION}"] = {
            "seconds_whole_tree": secs,
            "configs": SEMGREP_CONFIGS,
            "rules_counted": rules,
            "groups": {k: v.as_dict() for k, v in score(cases, det).items()},
        }
        det, secs = bandit_detections(src, args.work)
        tools[f"bandit {BANDIT_VERSION}"] = {
            "seconds_whole_tree": secs,
            "rule_map": BANDIT_RULES,
            "scope": "Python cases only",
            "groups": {k: v.as_dict() for k, v in score(cases, det, {"py"}).items()},
        }

    results = {
        "seed": args.seed,
        "cases": len(cases),
        "vulnerable": sum(c["vulnerable"] for c in cases),
        "safe": sum(not c["vulnerable"] for c in cases),
        "machine": f"{platform.machine()} {platform.system()} {platform.release()}",
        "python": sys.version.split()[0],
        "tools": tools,
        "mcpscan_bench_output": bench,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(results, indent=1) + "\n")
    args.out.with_suffix(".md").write_text(markdown(results))
    print(markdown(results))
    for name, t in tools.items():
        o = t["groups"]["overall"]
        print(f"{name}: recall {fmt(o['recall'])} FPR {fmt(o['fpr'])} in {t['seconds_whole_tree']:.2f}s (whole tree)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
